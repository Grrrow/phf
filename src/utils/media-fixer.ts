export function resolveVideoMedia(blok: any): any {
  if (!blok) return blok;

  const clone = { ...blok };
  let embedUrl = clone.embed_url || clone.cta_link?.cached_url || '';
  let imgUrl = clone.image?.filename || '';

  // Check if embedUrl or imgUrl contains a known dummy YouTube ID
  for (const [dummyId, replacement] of Object.entries(REAL_YOUTUBE_REPLACEMENTS)) {
    if (embedUrl.includes(dummyId) || imgUrl.includes(dummyId)) {
      clone.embed_url = replacement.realUrl;
      clone.image = {
        ...clone.image,
        filename: replacement.realThumb,
        fieldtype: 'asset'
      };
      return clone;
    }
  }

  // If it's a YouTube URL and has no valid image or has maxresdefault which might 404, fallback to hqdefault
  const match = embedUrl.match(/(?:youtu\.be\/|youtube\.com\/(?:embed\/|v\/|watch\?v=|watch\?.+&v=))([\w-]{11})/);
  if (match) {
    const ytId = match[1];
    if (!imgUrl || imgUrl.includes('maxresdefault.jpg')) {
      clone.image = {
        ...clone.image,
        filename: `https://i.ytimg.com/vi/${ytId}/hqdefault.jpg`,
        fieldtype: 'asset'
      };
    }
  }

  return clone;
}

